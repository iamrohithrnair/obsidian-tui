//! Compact base palettes that expand into full themes.
//!
//! A [`Seed`] is the ~20 colors a color scheme actually defines. Everything
//! else — which color a level-3 heading gets, how a "danger" callout is tinted,
//! what an unresolved graph node looks like — is Obsidian's design applied on
//! top, and lives in [`Theme::from_seed`](crate::Theme::from_seed).
//!
//! Adding a theme therefore means adding one `Seed` below and one entry in
//! [`crate::presets::ALL`].

/// The base colors of a color scheme.
///
/// Every field is a color string in the format described in [`crate::color`],
/// so a seed can use `reset`/ANSI names to inherit from the terminal.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct Seed {
    /// Theme identifier used in config, e.g. `catppuccin-mocha`.
    pub name: &'static str,
    pub dark: bool,

    /// Note pane background.
    pub bg: &'static str,
    /// A step away from `bg`: code blocks, the active editor line.
    pub bg_alt: &'static str,
    /// Sidebar background.
    pub bg2: &'static str,
    /// Ribbon and status bar background — the deepest surface.
    pub bg3: &'static str,
    pub border: &'static str,
    /// Row under the cursor.
    pub hover: &'static str,
    /// Row that is selected, and editor text selection.
    pub active: &'static str,

    pub text: &'static str,
    pub muted: &'static str,
    pub faint: &'static str,

    /// The scheme's signature color. Obsidian's is purple.
    pub accent: &'static str,

    pub red: &'static str,
    pub orange: &'static str,
    pub yellow: &'static str,
    pub green: &'static str,
    pub cyan: &'static str,
    pub blue: &'static str,
    pub purple: &'static str,
    pub pink: &'static str,
}

